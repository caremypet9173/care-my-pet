import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";
import AxeBuilder from "@axe-core/playwright";
test.use({ trace: "off", screenshot: "off", video: "off" });
test("pet form validation and local photo adjustment do not save before submission", async ({ page }, testInfo) => {
  test.skip(!process.env.PETS_TEST_CREDENTIALS, "Needs a test account");
  const credentials = JSON.parse(await readFile(process.env.PETS_TEST_CREDENTIALS!, "utf8"));
  await page.goto("/pl/login");
  await page.getByLabel("Adres e-mail").fill(credentials.email);
  await page.getByLabel("Hasło", { exact: true }).fill(credentials.password);
  await page.getByRole("button", { name: "Zaloguj się", exact: true }).click();
  await expect(page).toHaveURL(/\/pl\/app$/);
  await page.getByRole("button", { name: "Rozumiem", exact: true }).click();
  await page.goto("/pl/app/zwierzeta/nowe");
  let writes = 0;
  await page.route("**/functions/v1/pets", async route => { writes++; await route.abort(); });
  await page.route("**/storage/v1/object/pet-avatars/**", async route => { writes++; await route.abort(); });
  await page.screenshot({ path: `tmp/pet-registration-empty-${testInfo.project.name}.png`, fullPage: true });
  await page.getByRole("button", { name: "Utwórz kartotekę" }).click();
  await expect(page.locator(".pet-validation-summary")).toContainText("Podaj imię");
  await page.getByLabel("Imię").fill("Luna");
  await page.getByRole("radio", { name: "Kot Kot lub kotka" }).check();
  await expect(page.locator(".pet-validation-summary")).toHaveCount(0);
  await page.getByLabel("Dodaj zdjęcie", { exact: true }).setInputFiles({ name: "bad.svg", mimeType: "image/svg+xml", buffer: Buffer.from("<svg />") });
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Wybierz poprawne zdjęcie");
  await page.getByLabel("Dodaj zdjęcie", { exact: true }).setInputFiles("public/media/luna.png");
  const dialog = page.getByRole("dialog", { name: "Dopasuj zdjęcie" });
  await expect(dialog).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(page.locator(".pet-photo-preview img")).toHaveCount(0);
  await page.getByLabel("Dodaj zdjęcie", { exact: true }).setInputFiles("public/media/luna.png");
  await expect(dialog.getByRole("button", { name: "Zapisz zdjęcie" })).toBeEnabled();
  await page.setViewportSize({ width: 320, height: 780 });
  await expect.poll(() => dialog.evaluate(el => el.scrollWidth - el.clientWidth)).toBe(0);
  await dialog.getByRole("button", { name: "Zapisz zdjęcie" }).click();
  await expect(page.locator(".pet-photo-preview img")).toBeVisible();
  await expect(page.getByLabel("Imię")).toHaveValue("Luna");
  expect((await new AxeBuilder({ page }).include("main").analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(writes).toBe(0);
});
