import { test, expect } from "@playwright/test";
import { readFile, writeFile } from "node:fs/promises";
import AxeBuilder from "@axe-core/playwright";

// Opt-in integration check against the configured Supabase. Creates one marked pet.
// The captured ID must be cleaned up by an administrator after this test.
test.use({ trace: "off", screenshot: "off", video: "off" });
test("pet create, edit, conflict and persistence", async ({ page }, testInfo) => {
  test.setTimeout(60000);
  test.skip(!process.env.PETS_TEST_CREDENTIALS, "Needs an explicitly supplied test account file");
  const credentials = JSON.parse(await readFile(process.env.PETS_TEST_CREDENTIALS!, "utf8"));
  await page.goto("/pl/login");
  await page.getByLabel("Adres e-mail").fill(credentials.email);
  await page.getByLabel("Hasło", { exact: true }).fill(credentials.password);
  await page.getByRole("button", { name: "Zaloguj się", exact: true }).click();
  await expect(page).toHaveURL(/\/pl\/app$/);
  await page.getByRole("button", { name: "Rozumiem", exact: true }).click();
  await expect(page.locator(".household-account")).toContainText(credentials.email);
  await page.locator('a[href="/pl/app/zwierzeta/nowe"]').first().click();
  await page.getByRole("button", { name: "Utwórz kartotekę" }).click();
  await expect(page.locator(".pet-validation-summary")).toContainText("Wybierz kota lub psa");
  await expect(page.locator(".pet-validation-summary")).toContainText("Podaj imię pupila");
  await page.getByLabel("Imię").fill(`TEST AUTOMATYCZNY ${testInfo.project.name}`);
  await page.getByRole("radio", { name: "Kot Kot lub kotka" }).check();
  await expect(page.locator(".pet-validation-summary")).toHaveCount(0);
  await page.getByRole("radio", { name: "Samica", exact: true }).check();
  await page.getByLabel("Data urodzenia").fill("2020-04-02");
  await page.getByLabel("Data jest przybliżona").check();
  await page.locator(".pet-additional summary").click();
  await page.getByRole("radio", { name: "Mikroczip", exact: true }).check();
  await page.getByLabel("Numer identyfikacyjny").fill("123456789012345");
  await page.getByLabel("Dodaj zdjęcie", { exact: true }).setInputFiles("public/media/luna.png");
  const crop = page.getByRole("dialog", { name: "Dopasuj zdjęcie" });
  await expect(crop).toBeVisible();
  await expect(crop.getByRole("button", { name: "Zapisz zdjęcie" })).toBeEnabled();
  await crop.getByRole("slider", { name: "Skala powiększenia" }).fill("1.4");
  await crop.getByRole("button", { name: "Obróć o 90°" }).click();
  await crop.getByRole("slider", { name: "Przesunięcie poziome" }).fill("0.3");
  await page.screenshot({ path: `tmp/pets-crop-${testInfo.project.name}.png` });
  expect((await new AxeBuilder({ page }).include("dialog").analyze()).violations).toEqual([]);
  await crop.getByRole("button", { name: "Zapisz zdjęcie" }).click();
  await expect(crop).not.toBeVisible();
  expect((await new AxeBuilder({ page }).include("main").analyze()).violations).toEqual([]);
  await page.screenshot({ path: `tmp/pets-form-${testInfo.project.name}.png`, fullPage: true });
  const responsePromise = page.waitForResponse(r => r.url().includes("/functions/v1/pets") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Utwórz kartotekę" }).click();
  const response = await responsePromise;
  expect(response.status()).toBe(201);
  const created = (await response.json()).pet;
  await writeFile(`tmp/pets-test-${testInfo.project.name}.json`, JSON.stringify({ id: created.id, gospodarstwo_id: created.gospodarstwo_id, avatar_path: created.avatar_path }));
  expect(created.avatar_path).toMatch(/\.jpg$/);
  expect(created.data_urodzenia_przyblizona).toBe(true);
  await expect(page).toHaveURL(new RegExp(`/app/zwierzeta/${created.id}$`));
  await page.getByRole("link", { name: "Edytuj profil" }).click();
  await page.locator(".pet-additional summary").click();
  await page.getByLabel("Notatki opiekuna").fill("Notatka testowa po edycji.");
  await page.getByRole("button", { name: "Zapisz profil" }).click();
  await expect(page.getByText("Notatka testowa po edycji.")).toBeVisible();
  await page.reload();
  await expect(page.locator(".household-portrait img")).toBeVisible();
  expect(await page.locator(".household-portrait img").evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
  await expect(page.getByText("Notatka testowa po edycji.")).toBeVisible();
  await page.screenshot({ path: `tmp/pets-profile-${testInfo.project.name}.png`, fullPage: true });
  expect((await new AxeBuilder({ page }).include("main").analyze()).violations).toEqual([]);
  await page.getByRole("tab", { name: "Dokumenty", exact: true }).click();
  await expect(page.getByRole("tabpanel", { name: "Dokumenty" })).toContainText("w przygotowaniu");
  await page.getByRole("tab", { name: "Podsumowanie", exact: true }).click();
  await page.getByRole("link", { name: "Edytuj profil" }).click();
  await page.route("**/functions/v1/pets", async route => {
    const body = route.request().postDataJSON();
    await route.continue({ postData: JSON.stringify({ ...body, updated_at: created.updated_at }) });
  });
  await page.getByRole("button", { name: "Zapisz profil" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Profil zmienił się" })).toBeVisible();
  await page.unroute("**/functions/v1/pets");
  await page.goto("/en/app");
  await expect(page.getByRole("heading", { name: "Your pets and care at home" })).toBeVisible();
  await expect(page.getByRole("link").filter({ hasText: `TEST AUTOMATYCZNY ${testInfo.project.name}` })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `tmp/pets-list-${testInfo.project.name}.png`, fullPage: true });
  await page.goto(`/pl/app/zwierzeta/${created.id}/edytuj`);
  await page.getByRole("button", { name: "Usuń", exact: true }).click();
  await page.getByRole("button", { name: "Zapisz profil" }).click();
  await expect(page.getByText("Brak zdjęcia", { exact: true })).toBeVisible();
});
